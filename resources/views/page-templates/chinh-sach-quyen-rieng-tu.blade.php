<li>Thông tin nguồn truy cập khi gửi form: trang gửi form, trang bạn vào đầu tiên, tham số chiến dịch (UTM).</li>
<li>Dữ liệu thống kê qua Google Analytics 4: cookie gán một mã định danh ngẫu nhiên cho trình duyệt (không chứa tên, email), trang đã xem, thiết bị, vị trí ước lượng.</li>
<li>Kiểm tra chống gửi tự động của Cloudflare Turnstile khi bạn gửi form (tín hiệu kỹ thuật của trình duyệt).</li>
</ul>
