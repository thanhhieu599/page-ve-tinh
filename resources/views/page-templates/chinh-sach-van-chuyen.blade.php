<h2>Thời gian giao hàng</h2>
<p>[CẦN XÁC NHẬN: ví dụ nội thành 1–2 ngày làm việc kể từ khi xác nhận đơn; đơn số lượng lớn theo lịch thoả thuận.]</p>
<h2>Phí vận chuyển</h2>
<p>[CẦN XÁC NHẬN: miễn phí cho đơn từ … đồng trong khu vực …; đơn khác báo phí khi báo giá.]</p>
<h2>Kiểm tra và nhận hàng</h2>
<p>Bên nhận kiểm tra số lượng, quy cách và tình trạng hàng khi giao; ký biên bản giao nhận. Hàng sai, thiếu hoặc hư hỏng do vận chuyển được xử lý theo chính sách đổi trả.</p>
